export function createBlankCard(index = 1) {
  return {
    name: `未载入角色 ${index}`,
    alias: "等待导入 / 手动编辑",
    hp: 35,
    maxHp: 35,
    bodySp: 0,
    headSp: 0,
    deathPenalty: 0,
    int: 0,
    ref: 0,
    dex: 0,
    tech: 0,
    cool: 0,
    will: 0,
    move: 0,
    body: 0,
    emp: 0,
    skills: { ...blankSkills },
    weapons: [],
    source: null
  };
}

function card(patch) {
  return {
    ...createBlankCard(),
    ...patch,
    skills: { ...blankSkills, ...(patch.skills || {}) },
    weapons: patch.weapons || [],
    source: null
  };
}

